use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

#[allow(dead_code)]
#[path = "../build.rs"]
mod scanner;

const HEADER: &str = "// @generated by build.rs from direct src/items Rust files; do not edit.\n\n";
static NEXT_FIXTURE: AtomicUsize = AtomicUsize::new(0);

struct Fixture {
    root: PathBuf,
}

impl Fixture {
    fn new() -> Self {
        let sequence = NEXT_FIXTURE.fetch_add(1, Ordering::Relaxed);
        let root = std::env::temp_dir().join(format!(
            "dependency-declarations-reconcile-membership-{}-{sequence}",
            std::process::id()
        ));
        fs::create_dir(&root).expect("fixture directory must be created");
        Self { root }
    }

    fn path(&self) -> &Path {
        &self.root
    }

    fn write(&self, relative: &str, contents: &[u8]) {
        let path = self.root.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("fixture parent must be created");
        }
        fs::write(path, contents).expect("fixture item must be written");
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.root).expect("fixture directory must be removed");
    }
}

#[test]
fn direct_regular_rust_items_are_sorted_and_deterministic() {
    let fixture = Fixture::new();
    fixture.write("z_last.rs", b"pub const LAST: u8 = 2;");
    fixture.write("a_first.rs", b"pub const FIRST: u8 = 1;\n");
    fixture.write("notes.txt", b"not Rust\n");
    fixture.write("nested/hidden.rs", b"pub const HIDDEN: u8 = 3;\n");
    #[cfg(unix)]
    std::os::unix::fs::symlink(
        fixture.path().join("a_first.rs"),
        fixture.path().join("linked.rs"),
    )
    .expect("fixture symlink must be created");

    let expected = concat!(
        "// @generated by build.rs from direct src/items Rust files; do not edit.\n\n",
        "// source: a_first.rs\n",
        "pub const FIRST: u8 = 1;\n\n",
        "// source: z_last.rs\n",
        "pub const LAST: u8 = 2;\n",
    )
    .as_bytes();
    assert_eq!(scanner::render_items(fixture.path()).unwrap(), expected);
    assert_eq!(scanner::render_items(fixture.path()).unwrap(), expected);
}

#[test]
fn add_rename_and_remove_refresh_without_an_index() {
    let fixture = Fixture::new();
    fixture.write("b_existing.rs", b"pub const EXISTING: u8 = 1;\n");
    fixture.write("a_added.rs", b"pub const ADDED: u8 = 2;\n");
    let added = String::from_utf8(scanner::render_items(fixture.path()).unwrap()).unwrap();
    assert!(added.find("a_added.rs") < added.find("b_existing.rs"));

    fs::rename(
        fixture.path().join("a_added.rs"),
        fixture.path().join("c_renamed.rs"),
    )
    .expect("fixture item must be renamed");
    let renamed = String::from_utf8(scanner::render_items(fixture.path()).unwrap()).unwrap();
    assert!(!renamed.contains("a_added.rs"));
    assert!(renamed.contains("c_renamed.rs"));

    fs::remove_file(fixture.path().join("c_renamed.rs")).expect("fixture item must be removed");
    let removed = String::from_utf8(scanner::render_items(fixture.path()).unwrap()).unwrap();
    assert!(!removed.contains("c_renamed.rs"));
    assert!(removed.contains("b_existing.rs"));
}

#[test]
fn invalid_direct_rust_names_fail_closed() {
    for name in ["Bad.rs", "bad-name.rs", "bad__name.rs", "bad_.rs"] {
        let fixture = Fixture::new();
        fixture.write(name, b"pub const ITEM: u8 = 1;\n");
        let error = scanner::render_items(fixture.path()).unwrap_err();
        assert!(
            error.contains("invalid direct Rust item name"),
            "{name}: {error}"
        );
    }
}

#[cfg(unix)]
#[test]
fn non_utf8_direct_rust_names_fail_closed() {
    use std::ffi::OsString;
    use std::os::unix::ffi::OsStringExt;

    let name = OsString::from_vec(b"\xff.rs".to_vec());
    let error = scanner::validate_item_name(&name).unwrap_err();
    assert!(error.contains("valid UTF-8"), "{error}");
}

#[test]
fn absent_items_directory_emits_only_the_header() {
    let fixture = Fixture::new();
    let absent = fixture.path().join("src/items");
    assert_eq!(scanner::render_items(&absent).unwrap(), HEADER.as_bytes());
}
