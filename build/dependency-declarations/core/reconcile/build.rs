use std::error::Error;
use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};

const HEADER: &[u8] =
    b"// @generated by build.rs from direct src/items Rust files; do not edit.\n\n";

pub fn validate_item_name(name: &OsStr) -> Result<String, String> {
    let name = name
        .to_str()
        .ok_or_else(|| "direct Rust item name is not valid UTF-8".to_owned())?;
    let stem = name
        .strip_suffix(".rs")
        .ok_or_else(|| format!("invalid direct Rust item name {name}"))?;
    let valid = stem.as_bytes().first().is_some_and(u8::is_ascii_lowercase)
        && stem
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
        && !stem.ends_with('_')
        && !stem.contains("__");
    if !valid {
        return Err(format!("invalid direct Rust item name {name}"));
    }
    Ok(name.to_owned())
}

pub fn render_items(item_dir: &Path) -> Result<Vec<u8>, String> {
    let entries = match fs::read_dir(item_dir) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(HEADER.to_vec()),
        Err(error) => return Err(format!("cannot read {}: {error}", item_dir.display())),
    };
    let mut items: Vec<(String, PathBuf)> = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| format!("cannot read membership entry: {error}"))?;
        let file_type = entry
            .file_type()
            .map_err(|error| format!("cannot inspect {}: {error}", entry.path().display()))?;
        let path = entry.path();
        if !file_type.is_file() || path.extension() != Some(OsStr::new("rs")) {
            continue;
        }
        items.push((validate_item_name(&entry.file_name())?, path));
    }
    items.sort_by(|left, right| left.0.as_bytes().cmp(right.0.as_bytes()));

    let mut output = HEADER.to_vec();
    let item_count = items.len();
    for (index, (name, path)) in items.into_iter().enumerate() {
        let contents = fs::read(&path)
            .map_err(|error| format!("cannot read direct Rust item {}: {error}", path.display()))?;
        std::str::from_utf8(&contents)
            .map_err(|_| format!("direct Rust item {} is not valid UTF-8", path.display()))?;
        output.extend_from_slice(b"// source: ");
        output.extend_from_slice(name.as_bytes());
        output.push(b'\n');
        output.extend_from_slice(&contents);
        if !contents.ends_with(b"\n") {
            output.push(b'\n');
        }
        if index + 1 < item_count {
            output.push(b'\n');
        }
    }
    Ok(output)
}

pub fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo:rerun-if-changed=src/items");
    let manifest_dir =
        std::env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR is not set")?;
    let out_dir = std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?;
    let generated = render_items(&PathBuf::from(manifest_dir).join("src/items"))
        .map_err(std::io::Error::other)?;
    fs::write(Path::new(&out_dir).join("items.generated.rs"), generated)?;
    Ok(())
}
