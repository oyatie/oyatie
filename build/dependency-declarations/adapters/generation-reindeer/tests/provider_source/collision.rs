use std::fs;
use std::path::Path;

use crate::cargo_build::build_reindeer_binary;
use crate::support::{materialized_fixture, parse_artifact, pinned_source_root, run_artifact};

#[test]
#[ignore = "requires the exact upstream Reindeer source snapshot"]
fn artifact_public_aliases_are_version_qualified_when_logical_names_collide() {
    let snapshot = crate::support::source_snapshot(&pinned_source_root());
    let (_, fixture) = materialized_fixture(&snapshot);
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let binary = build_reindeer_binary(&cargo, fixture.path());
    let root = fixture.path().join("qualification-collision");
    write_collision_workspace(&root);

    let bytes = run_artifact(&binary, &root, "public-name-collision");
    let artifact = parse_artifact(&bytes);
    let buck = std::str::from_utf8(artifact.rendered_buck).unwrap();

    assert!(buck.contains("name = \"fixture-0.4\""), "{buck}");
    assert!(buck.contains("name = \"fixture-0.5\""));
    assert!(!buck.contains("name = \"fixture\""));
    assert!(buck.contains("name = \"fixture-0.4-local\""));
    assert!(buck.contains("name = \"fixture-0.5-local\""));
    assert!(buck.contains("\"CARGO_PKG_VERSION\": \"0.4.13\""));
    assert!(buck.contains("\"CARGO_PKG_VERSION\": \"0.5.3\""));
    assert!(buck.contains("crate_root = \"local/fixture-04/src/lib.rs\""));
    assert!(buck.contains("crate_root = \"local/fixture-05/src/lib.rs\""));
}

fn write_collision_workspace(root: &Path) {
    let third_party = root.join("third-party");
    for relative in [
        "apps/consumer-04/src",
        "apps/consumer-05/src",
        "local/fixture-04/src",
        "local/fixture-05/src",
    ] {
        fs::create_dir_all(third_party.join(relative)).unwrap();
    }
    fs::write(
        root.join("reindeer.toml"),
        concat!(
            "third_party_dir = \"third-party\"\n",
            "vendor = false\n",
            "cargo_env = [\"CARGO_PKG_NAME\", \"CARGO_PKG_VERSION\"]\n",
            "\n",
            "[buck]\n",
            "rust_library = \"cargo.rust_library\"\n",
            "rust_binary = \"cargo.rust_binary\"\n",
            "buckfile_imports = \"load(\\\"@prelude//rust:cargo_package.bzl\\\", ",
            "\\\"cargo\\\")\"\n",
        ),
    )
    .unwrap();
    fs::write(
        third_party.join("Cargo.toml"),
        concat!(
            "[workspace]\n",
            "members = [\"apps/consumer-04\", \"apps/consumer-05\"]\n",
            "exclude = [\"local/fixture-04\", \"local/fixture-05\"]\n",
            "resolver = \"3\"\n",
        ),
    )
    .unwrap();
    fs::write(
        third_party.join("Cargo.lock"),
        concat!(
            "# This file is automatically @generated by Cargo.\n",
            "# It is not intended for manual editing.\n",
            "version = 4\n",
            "\n",
            "[[package]]\n",
            "name = \"consumer-04\"\n",
            "version = \"1.0.0\"\n",
            "dependencies = [\n",
            " \"fixture 0.4.13\",\n",
            "]\n",
            "\n",
            "[[package]]\n",
            "name = \"consumer-05\"\n",
            "version = \"1.0.0\"\n",
            "dependencies = [\n",
            " \"fixture 0.5.3\",\n",
            "]\n",
            "\n",
            "[[package]]\n",
            "name = \"fixture\"\n",
            "version = \"0.4.13\"\n",
            "\n",
            "[[package]]\n",
            "name = \"fixture\"\n",
            "version = \"0.5.3\"\n",
        ),
    )
    .unwrap();
    write_package(
        &third_party.join("apps/consumer-04"),
        "consumer-04",
        "fixture = { path = \"../../local/fixture-04\" }",
    );
    write_package(
        &third_party.join("apps/consumer-05"),
        "consumer-05",
        "fixture = { path = \"../../local/fixture-05\" }",
    );
    write_package(&third_party.join("local/fixture-04"), "fixture", "");
    write_package(&third_party.join("local/fixture-05"), "fixture", "");
    fs::write(
        third_party.join("local/fixture-04/Cargo.toml"),
        package_manifest("fixture", "0.4.13", ""),
    )
    .unwrap();
    fs::write(
        third_party.join("local/fixture-05/Cargo.toml"),
        package_manifest("fixture", "0.5.3", ""),
    )
    .unwrap();
}

fn write_package(root: &Path, name: &str, dependency: &str) {
    fs::write(
        root.join("Cargo.toml"),
        package_manifest(name, "1.0.0", dependency),
    )
    .unwrap();
    fs::write(root.join("src/lib.rs"), "pub fn marker() {}\n").unwrap();
}

fn package_manifest(name: &str, version: &str, dependency: &str) -> String {
    let mut manifest = format!(
        "[package]\nname = \"{name}\"\nversion = \"{version}\"\nedition = \"2024\"\npublish = false\n"
    );
    if !dependency.is_empty() {
        manifest.push_str("\n[dependencies]\n");
        manifest.push_str(dependency);
        manifest.push('\n');
    }
    manifest
}
