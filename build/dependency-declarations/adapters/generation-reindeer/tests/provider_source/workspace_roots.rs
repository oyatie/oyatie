use std::fs;
use std::path::Path;

use crate::cargo_build::build_reindeer_binary;
use crate::support::{materialized_fixture, parse_artifact, pinned_source_root, run_artifact};

#[test]
#[ignore = "requires the exact upstream Reindeer source snapshot"]
fn artifact_traverses_non_workspace_dependency_kinds_without_generating_workspace_rules() {
    let snapshot = crate::support::source_snapshot(&pinned_source_root());
    let (_, fixture) = materialized_fixture(&snapshot);
    let cargo = std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into());
    let binary = build_reindeer_binary(&cargo, fixture.path());
    let root = fixture.path().join("qualification-workspace-roots");
    write_workspace(&root);

    let bytes = run_artifact(&binary, &root, "workspace-roots");
    let artifact = parse_artifact(&bytes);
    let buck = std::str::from_utf8(artifact.rendered_buck).unwrap();

    for name in ["normal-fixture", "build-fixture", "dev-fixture"] {
        assert!(buck.contains(&format!("name = \"{name}\"")), "{buck}");
    }
    assert_eq!(
        buck.matches("visibility = [\"PUBLIC\"]").count(),
        3,
        "{buck}"
    );
    assert!(!buck.contains("name = \"consumer\""));
    assert!(!buck.contains("consumer-build-script"));
}

fn write_workspace(root: &Path) {
    let third_party = root.join("third-party");
    for relative in [
        "apps/consumer/src",
        "local/normal-fixture/src",
        "local/build-fixture/src",
        "local/dev-fixture/src",
    ] {
        fs::create_dir_all(third_party.join(relative)).unwrap();
    }
    fs::write(
        root.join("reindeer.toml"),
        concat!(
            "third_party_dir = \"third-party\"\n",
            "vendor = false\n",
            "unresolved_fixup_error = true\n",
            "\n",
            "[buck]\n",
            "rust_library = \"cargo.rust_library\"\n",
            "rust_binary = \"cargo.rust_binary\"\n",
            "buckfile_imports = \"load(\\\"@prelude//rust:cargo_package.bzl\\\", ",
            "\\\"cargo\\\")\"\n",
        ),
    )
    .unwrap();
    fs::write(
        third_party.join("Cargo.toml"),
        concat!(
            "[workspace]\n",
            "members = [\"apps/consumer\"]\n",
            "exclude = [\n",
            "  \"local/normal-fixture\",\n",
            "  \"local/build-fixture\",\n",
            "  \"local/dev-fixture\",\n",
            "]\n",
            "resolver = \"3\"\n",
        ),
    )
    .unwrap();
    fs::write(
        third_party.join("Cargo.lock"),
        concat!(
            "# This file is automatically @generated by Cargo.\n",
            "# It is not intended for manual editing.\n",
            "version = 4\n",
            "\n",
            "[[package]]\n",
            "name = \"build-fixture\"\n",
            "version = \"1.0.0\"\n",
            "\n",
            "[[package]]\n",
            "name = \"consumer\"\n",
            "version = \"1.0.0\"\n",
            "dependencies = [\n",
            " \"build-fixture\",\n",
            " \"dev-fixture\",\n",
            " \"normal-fixture\",\n",
            "]\n",
            "\n",
            "[[package]]\n",
            "name = \"dev-fixture\"\n",
            "version = \"1.0.0\"\n",
            "\n",
            "[[package]]\n",
            "name = \"normal-fixture\"\n",
            "version = \"1.0.0\"\n",
        ),
    )
    .unwrap();
    fs::write(
        third_party.join("apps/consumer/Cargo.toml"),
        concat!(
            "[package]\n",
            "name = \"consumer\"\n",
            "version = \"1.0.0\"\n",
            "edition = \"2024\"\n",
            "publish = false\n",
            "\n",
            "[dependencies]\n",
            "normal-fixture = { path = \"../../local/normal-fixture\" }\n",
            "\n",
            "[build-dependencies]\n",
            "build-fixture = { path = \"../../local/build-fixture\" }\n",
            "\n",
            "[dev-dependencies]\n",
            "dev-fixture = { path = \"../../local/dev-fixture\" }\n",
        ),
    )
    .unwrap();
    fs::write(
        third_party.join("apps/consumer/src/lib.rs"),
        "pub fn marker() {}\n",
    )
    .unwrap();
    fs::write(third_party.join("apps/consumer/build.rs"), "fn main() {}\n").unwrap();
    for name in ["normal-fixture", "build-fixture", "dev-fixture"] {
        let package = third_party.join("local").join(name);
        fs::write(
            package.join("Cargo.toml"),
            format!(
                "[package]\nname = \"{name}\"\nversion = \"1.0.0\"\nedition = \"2024\"\npublish = false\n"
            ),
        )
        .unwrap();
        fs::write(package.join("src/lib.rs"), "pub fn marker() {}\n").unwrap();
    }
}
